package com.petstore.order.security;

import jakarta.annotation.PreDestroy;
import org.springframework.stereotype.Component;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

@Component
public class EntraUserStore {

    private final Connection connection;

    public EntraUserStore() throws SQLException {
        connection = DriverManager.getConnection("jdbc:h2:mem:entra;DB_CLOSE_DELAY=-1", "sa", "");
        try (Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS entra_user (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        oid VARCHAR(128) NOT NULL UNIQUE,
                        email VARCHAR(200),
                        given_name VARCHAR(100),
                        family_name VARCHAR(100)
                    )
                    """);
        }
    }

    public synchronized long save(String oid, String email, String givenName, String familyName) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement("""
                MERGE INTO entra_user (oid, email, given_name, family_name)
                KEY (oid) VALUES (?, ?, ?, ?)
                """)) {
            statement.setString(1, oid);
            statement.setString(2, email);
            statement.setString(3, givenName);
            statement.setString(4, familyName);
            statement.executeUpdate();
        }
        try (PreparedStatement statement = connection.prepareStatement(
                "SELECT id FROM entra_user WHERE oid = ?")) {
            statement.setString(1, oid);
            try (ResultSet rows = statement.executeQuery()) {
                if (rows.next()) {
                    return rows.getLong("id");
                }
            }
        }
        throw new SQLException("Entra user was not stored");
    }

    @PreDestroy
    void close() throws SQLException {
        connection.close();
    }
}
